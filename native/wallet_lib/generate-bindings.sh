#!/usr/bin/env bash
# Regenerates native/veil_wallet/src/sys/bindings.rs from the wallet
# library's C header. Run after changing the pinned library version or the
# list of functions below.
#
# Usage: generate-bindings.sh /path/to/monero_wallet2_api_c.h
# Needs: bindgen-cli (cargo install bindgen-cli) and libclang.
set -euo pipefail

header="${1:?path to monero_wallet2_api_c.h}"
out="$(cd "$(dirname "$0")/.." && pwd)/veil_wallet/src/sys/bindings.rs"

# Only the functions Veil calls. Keeping the list short keeps the unsafe
# surface small and makes a missing symbol a load-time error.
functions='MONERO_(free'
functions+='|WalletManagerFactory_getWalletManager'
functions+='|WalletManagerFactory_setLogLevel'
functions+='|WalletManager_(createWalletFromPolyseed|recoveryWallet|openWallet|closeWallet|walletExists|errorString)'
functions+='|Wallet_(createPolyseed|getPolyseed|seed|status|errorString|address|nettype|store|init'
functions+='|setTrustedDaemon|setRefreshFromBlockHeight|getRefreshFromBlockHeight|setRecoveringFromSeed'
functions+='|setAllowMismatchedDaemonVersion|setBackgroundRefresh|connected|refresh|balance|unlockedBalance'
functions+='|blockChainHeight'
functions+='|daemonBlockChainHeight|daemonBlockChainTargetHeight|addressValid|numSubaddresses|addSubaddress'
functions+='|createTransaction|history|stop|setPassword|setCacheAttribute|getCacheAttribute)'
functions+='|PendingTransaction_(status|errorString|commit|amount|fee|txid|subaddrIndices)'
functions+='|TransactionHistory_(count|transaction|refresh)'
functions+='|TransactionInfo_(direction|isPending|isFailed|amount|fee|blockHeight|confirmations|hash|timestamp|subaddrIndex|subaddrAccount)'
functions+='|cw_getWalletListener|cw_WalletListener_height)'

bindgen "$header" \
  --dynamic-loading MoneroC \
  --dynamic-link-require-all \
  --allowlist-function "$functions" \
  --no-layout-tests \
  --no-doc-comments \
  --rust-target 1.82 \
  --raw-line '// Generated by native/wallet_lib/generate-bindings.sh. Do not edit.' \
  -o "$out"
echo "wrote $out"
